-- House Assist database schema for Supabase Postgres.
-- Run this once in Supabase Dashboard > SQL Editor.

-- Keep House Assist's private account model separate from existing public tables.
create schema if not exists house_assist;

create table if not exists house_assist.users (
  id uuid primary key default gen_random_uuid(),
  username text not null,
  password_hash text,
  role text not null check (role in ('customer', 'helper')),
  location text not null,
  created_at bigint not null
);
create unique index if not exists users_username_lower_uq on house_assist.users (lower(username));
alter table house_assist.users alter column password_hash drop not null;

create table if not exists house_assist.helpers (
  id bigint generated by default as identity primary key,
  user_id uuid unique references house_assist.users(id) on delete cascade,
  name text not null,
  location text not null,
  services text not null,
  price integer not null check (price > 0),
  phone text not null default '',
  rating double precision not null default 0 check (rating >= 0 and rating <= 5),
  rating_count integer not null default 0 check (rating_count >= 0)
);

create table if not exists house_assist.sessions (
  token_hash text primary key,
  user_id uuid references house_assist.users(id) on delete cascade,
  role text not null check (role in ('customer', 'helper', 'admin')),
  expires_at bigint not null
);

create table if not exists house_assist.preferences (
  user_id uuid primary key references house_assist.users(id) on delete cascade,
  theme text not null default 'Ocean',
  layout text not null default 'grid' check (layout in ('grid', 'list')),
  compact boolean not null default false,
  colors text not null default '[]'
);

create table if not exists house_assist.hires (
  id bigint generated by default as identity primary key,
  customer_id uuid not null references house_assist.users(id),
  helper_id bigint not null references house_assist.helpers(id),
  payment_method text not null check (payment_method in ('cash', 'bank', 'momo')),
  payment_detail text not null default '',
  customer_paid boolean not null default false,
  helper_received boolean not null default false,
  created_at bigint not null,
  check (not helper_received or customer_paid)
);

create table if not exists house_assist.ratings (
  id bigint generated by default as identity primary key,
  hire_id bigint not null unique references house_assist.hires(id) on delete cascade,
  customer_id uuid not null references house_assist.users(id),
  helper_id bigint not null references house_assist.helpers(id),
  stars integer check (stars between 1 and 5),
  recommendation text not null default '',
  created_at bigint not null,
  check (stars is not null or length(trim(recommendation)) > 0)
);

create table if not exists house_assist.settings (
  key text primary key,
  value text not null
);

create index if not exists helpers_location_idx on house_assist.helpers (location);
create index if not exists hires_customer_created_idx on house_assist.hires (customer_id, created_at desc);
create index if not exists hires_helper_created_idx on house_assist.hires (helper_id, created_at desc);
create index if not exists ratings_helper_idx on house_assist.ratings (helper_id);

-- Passwords are owned by Supabase Auth (auth.users), not this application table.
-- password_hash remains nullable for compatibility with the earlier custom-auth schema.
-- The Flask server connects with the private database connection string.
-- Keep direct Supabase Data API access closed unless you add explicit policies.
alter table house_assist.users enable row level security;
alter table house_assist.helpers enable row level security;
alter table house_assist.sessions enable row level security;
alter table house_assist.preferences enable row level security;
alter table house_assist.hires enable row level security;
alter table house_assist.ratings enable row level security;
alter table house_assist.settings enable row level security;
